<?php

declare(strict_types=1);

namespace MiniForge\Database;

use InvalidArgumentException;
use MiniForge\Exceptions\DatabaseException;
use PDO;
use PDOException;
use PDOStatement;

/**
 * Thin wrapper around PDO.
 *
 * The connection is configured to throw exceptions, return associative
 * arrays and use real (non-emulated) prepared statements.
 */
final class Connection
{
    public function __construct(private readonly PDO $pdo)
    {
        $this->pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
        $this->pdo->setAttribute(PDO::ATTR_DEFAULT_FETCH_MODE, PDO::FETCH_ASSOC);
        $this->pdo->setAttribute(PDO::ATTR_EMULATE_PREPARES, false);
    }

    /**
     * Opens a SQLite connection from configuration.
     *
     * @param array<string, mixed> $config ['driver' => 'sqlite', 'path' => file path or ':memory:']
     */
    public static function fromConfig(array $config): self
    {
        $driver = $config['driver'] ?? 'sqlite';
        if ($driver !== 'sqlite') {
            throw new InvalidArgumentException(sprintf('Unsupported database driver [%s]. Only "sqlite" is supported.', (string) $driver));
        }

        $path = $config['path'] ?? null;
        if (!is_string($path) || $path === '') {
            throw new InvalidArgumentException('The SQLite database path must be a non-empty string.');
        }

        if ($path !== ':memory:' && !is_dir(dirname($path))) {
            throw new DatabaseException(sprintf('The directory of the SQLite database [%s] does not exist.', $path));
        }

        try {
            $connection = new self(new PDO('sqlite:' . $path));
        } catch (PDOException $exception) {
            throw new DatabaseException('Could not open the SQLite database.', 0, $exception);
        }

        $connection->pdo->exec('PRAGMA foreign_keys = ON');

        return $connection;
    }

    public function driverName(): string
    {
        return (string) $this->pdo->getAttribute(PDO::ATTR_DRIVER_NAME);
    }

    /**
     * Runs a SELECT and returns all rows.
     *
     * Values are ALWAYS bound through a prepared statement: never concatenate
     * user input into $sql.
     *
     * @param array<int|string, scalar|null> $params Positional (?) or named (:name) values
     * @return list<array<string, mixed>>
     */
    public function select(string $sql, array $params = []): array
    {
        /** @var list<array<string, mixed>> */
        return $this->run($sql, $params)->fetchAll();
    }

    /**
     * Runs a SELECT and returns the first row, or null when there is none.
     *
     * @param array<int|string, scalar|null> $params
     * @return array<string, mixed>|null
     */
    public function selectOne(string $sql, array $params = []): ?array
    {
        $row = $this->run($sql, $params)->fetch();

        /** @var array<string, mixed>|false $row */
        return $row === false ? null : $row;
    }

    /**
     * Runs an INSERT / UPDATE / DELETE and returns the number of affected rows.
     *
     * @param array<int|string, scalar|null> $params
     */
    public function execute(string $sql, array $params = []): int
    {
        return $this->run($sql, $params)->rowCount();
    }

    /**
     * Executes a trusted multi-statement SQL script (e.g. a schema file).
     *
     * Scripts cannot take parameters: never pass user input here.
     */
    public function executeScript(string $sql): void
    {
        try {
            $this->pdo->exec($sql);
        } catch (PDOException $exception) {
            throw new DatabaseException(sprintf('Database script failed: %s', $exception->getMessage()), 0, $exception);
        }
    }

    /**
     * Identifier generated by the last INSERT.
     */
    public function lastInsertId(): int
    {
        return (int) $this->pdo->lastInsertId();
    }

    /**
     * @param array<int|string, scalar|null> $params
     */
    private function run(string $sql, array $params): PDOStatement
    {
        try {
            $statement = $this->pdo->prepare($sql);

            foreach ($params as $key => $value) {
                $statement->bindValue(is_int($key) ? $key + 1 : ':' . ltrim($key, ':'), $value, match (true) {
                    is_int($value) => PDO::PARAM_INT,
                    is_bool($value) => PDO::PARAM_BOOL,
                    $value === null => PDO::PARAM_NULL,
                    default => PDO::PARAM_STR,
                });
            }

            $statement->execute();

            return $statement;
        } catch (PDOException $exception) {
            throw new DatabaseException(sprintf('Database query failed: %s', $exception->getMessage()), 0, $exception);
        }
    }
}
